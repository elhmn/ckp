package cmd

import (
	"fmt"
	"io/ioutil"
	"os"
	"strings"

	"github.com/elhmn/ckp/internal/config"
	"github.com/elhmn/ckp/internal/store"
	"github.com/mitchellh/go-homedir"
	"github.com/spf13/cobra"
)

const (
	ckpAliasesHeader  = "## File generated by ckp. DO NOT EDIT\n"
	ckpSourceComment  = "# ckp aliases"
	ckpSourceLine     = "source %s"
)

//NewSyncAliasCommand creates a new cobra command for the sync alias command
func NewSyncAliasCommand(conf config.Config) *cobra.Command {
	command := &cobra.Command{
		Use:   "alias",
		Short: "will sync your aliases",
		Long: `will add your alias in a ~/.ckp/ckp_aliases file and reference them in your main rc file

	example: ckp sync alias
	Will sync your aliases in a ~/.ckp/ckp_aliases file and add a source reference in your main rc file
`,
		Run: func(cmd *cobra.Command, args []string) {
			if err := syncAliasCommand(cmd, args, conf); err != nil {
				fmt.Fprintf(conf.OutWriter, "Error: %s\n", err)
				return
			}
		},
	}

	return command
}

func syncAliasCommand(cmd *cobra.Command, args []string, conf config.Config) error {
	//Setup spinner
	conf.Spin.Start()
	defer conf.Spin.Stop()

	storeFilePath, err := config.GetStoreFilePath(conf)
	if err != nil {
		return fmt.Errorf("failed to get store file path: %s", err)
	}

	conf.Spin.Message(" loading store...")
	_, storeData, _, err := loadStore(storeFilePath)
	if err != nil {
		return fmt.Errorf("failed to load store: %s", err)
	}

	aliasesFilePath, err := config.GetAliasesFilePath(conf)
	if err != nil {
		return fmt.Errorf("failed to get aliases file path: %s", err)
	}

	conf.Spin.Message(" writing aliases...")
	if err := writeAliasesFile(aliasesFilePath, storeData); err != nil {
		return fmt.Errorf("failed to write aliases file: %s", err)
	}

	conf.Spin.Message(" updating rc file...")
	if err := addSourceLineToRCFile(aliasesFilePath); err != nil {
		return fmt.Errorf("failed to update rc file: %s", err)
	}

	fmt.Fprintf(conf.OutWriter, "\nYour aliases were successfully synced!\n")
	return nil
}

func writeAliasesFile(aliasesFilePath string, storeData *store.Store) error {
	content := ckpAliasesHeader
	for _, script := range storeData.Scripts {
		if script.Code.Alias != "" {
			// Escape single quotes in content and trim trailing newline
			escapedContent := strings.ReplaceAll(strings.TrimRight(script.Code.Content, "\n"), "'", `'\''`)
			content += fmt.Sprintf("alias %s='%s'\n", script.Code.Alias, escapedContent)
		}
	}
	return ioutil.WriteFile(aliasesFilePath, []byte(content), 0666)
}

func addSourceLineToRCFile(aliasesFilePath string) error {
	rcFile, err := findRCFile()
	if err != nil {
		return err
	}

	if rcFile == "" {
		return nil
	}

	sourceLine := fmt.Sprintf(ckpSourceLine, aliasesFilePath)

	content, err := ioutil.ReadFile(rcFile)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("failed to read rc file %s: %s", rcFile, err)
	}

	// Check if source line already exists
	if strings.Contains(string(content), sourceLine) {
		return nil
	}

	// Append source line
	newContent := string(content)
	if len(newContent) > 0 && !strings.HasSuffix(newContent, "\n") {
		newContent += "\n"
	}
	newContent += fmt.Sprintf("\n%s\n%s\n", ckpSourceComment, sourceLine)

	return ioutil.WriteFile(rcFile, []byte(newContent), 0666)
}

func findRCFile() (string, error) {
	home, err := homedir.Dir()
	if err != nil {
		return "", fmt.Errorf("failed to read home directory: %s", err)
	}

	candidates := []string{
		fmt.Sprintf("%s/.zshrc", home),
		fmt.Sprintf("%s/.bashrc", home),
		fmt.Sprintf("%s/.bash_profile", home),
	}

	for _, candidate := range candidates {
		if _, err := os.Stat(candidate); err == nil {
			return candidate, nil
		}
	}

	return "", nil
}
